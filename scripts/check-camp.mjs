import fs from 'node:fs';
import create from '../public/engine/doom.js';
import assert from 'node:assert/strict';
const get=n=>fs.readFileSync(new URL('../public/engine/'+n,import.meta.url));
globalThis.ImageData=class {constructor(w,h){this.data=new Uint8ClampedArray(w*h*4)}};
let pixels;
const canvas={getContext:()=>({putImageData:f=>pixels=f.data})};
const m=await create({canvas,wasmBinary:get('doom.wasm'),print:()=>{},preRun:[m=>{for(const n of ['freedoom2.wad','tarikh.wad'])m.FS.writeFile('/'+n,get(n))}]});
const tick=n=>{for(let i=0;i<n;i++)m._th_tick()};
m._th_level(1);tick(30);m._th_key(119,1);tick(25);
fs.writeFileSync('../tools/build-temp/camp.rgba',pixels);
tick(230);console.log('Closed gate',m._th_x(),m._th_y());assert(m._th_x()>900&&m._th_x()<960);
m._th_gate(1);tick(100);console.log('Open gate',m._th_x(),m._th_y());assert(m._th_x()>1300);
m._th_key(119,0);m._th_weapon();tick(30);m._th_key(163,1);tick(12);m._th_key(163,0);
m._th_level(1);tick(45);
const quiver=m._th_arrows();
m._th_attack(1);m._th_attack(0);tick(24);
assert.equal(m._th_arrows(),quiver-1,'A tap between frames must launch one arrow');
m._th_equip(2);tick(35);assert.equal(m._th_equipped(),2);
m._th_attack(1);tick(45);m._th_attack(0);assert.equal(m._th_arrows(),quiver-1);
m._th_equip(1);tick(35);assert.equal(m._th_equipped(),1);
const speakers=new Set();m._th_key(119,1);
for(let i=0;i<150;i++){tick(1);speakers.add(m._th_speaker());}
m._th_key(119,0);assert(speakers.has(2),'Guard must be reachable from the trail');
console.log('Tap fired one arrow, sword did not consume arrows, bow re-equipped, nearby speakers:',[...speakers]);
m._th_level(1);tick(45);
const heading=m._th_angle();
m._th_turnaround();tick(1);assert.equal((m._th_angle()-heading)&65535,32768);
m._th_key(0xac,1);tick(12);m._th_key(0xac,0);tick(2);
const left=m._th_angle();assert.notEqual(left,(heading+32768)&65535);
m._th_key(0xae,1);tick(12);m._th_key(0xae,0);tick(2);assert.notEqual(m._th_angle(),left);
console.log('Verified half turn and both arrow keys');
const initialAngle=m._th_angle();
m._th_look(120);tick(1);
const clockwise=(initialAngle-m._th_angle())&65535;
assert(clockwise>0&&clockwise<32768);
m._th_look(-120);tick(1);assert.equal(m._th_angle(),initialAngle);
