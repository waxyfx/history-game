// Writes supabase/migrations/024_trial_explanations.sql from the story modules (kk) and the Russian packs (ru).
// Audit №14 follow-up: a production build ships no trial explanations either (they named the right option, e.g.
// «Аң стилі…» for saka_gold), so the server keeps them and gives each one out only after the player's choice.
// Usage: node scripts/explanations-sql.mjs   (tests/explanations.test.mjs fails when the file is out of date)
import {writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {loadLevel, LEVEL_IDS} from '../src/rpg/levels.js';

const pick = (v, lang) => (v && typeof v === 'object' ? v[lang] : lang === 'kk' ? v : null) || null;
// Every trial of every level: [level, id, kk, ru]
export async function explanationRows() {
  const rows = [];
  for (const n of LEVEL_IDS) {
    const L = await loadLevel(n);
    for (const q of Object.values(L.HISTORICAL_QUIZZES || {})) if (q.explanation) rows.push([n, q.id, q.explanation, q.ru?.explanation || null]);
    (L.BONUS_QUIZ?.questions || []).forEach((q, i) => {
      const id = L.BONUS_META?.[i]?.id;
      if (id && q.e) rows.push([n, id, pick(q.e, 'kk'), pick(q.e, 'ru')]);
    });
  }
  return rows;
}

const lit = s => s == null ? 'null' : "'" + String(s).replaceAll("'", "''") + "'";
export function explanationsSQL(rows) {
  return `-- Migration 024: trial explanations leave the browser (audit №14 follow-up; generated by scripts/explanations-sql.mjs —
-- edit the story modules and src/rpg/ru/mapNN.js, then run the script; do not edit this file by hand).
-- The answer keys left in migration 021, but each trial's explanation still named the right option. A production build
-- strips them (scripts/strip-answer-keys.mjs); trial_explain hands them out by the same rule as trial_check:
-- a teacher or admin, a player who has finished the level, or a trial the player has already answered.

create table if not exists private.trial_explanations (
  level_id int not null,
  quiz_id text not null,
  kk text not null,
  ru text,
  primary key (level_id, quiz_id)
);
revoke all on private.trial_explanations from public;

insert into private.trial_explanations (level_id, quiz_id, kk, ru) values
${rows.map(([n, id, kk, ru]) => `  (${n}, ${lit(id)}, ${lit(kk)}, ${lit(ru)})`).join(',\n')}
on conflict (level_id, quiz_id) do update set kk = excluded.kk, ru = excluded.ru;

create or replace function public.trial_explain(p_level int, p_quizzes text[]) returns jsonb language plpgsql stable security definer set search_path='' as $$
declare u uuid := private.require_user(); open_all boolean;
begin
  if p_quizzes is null or cardinality(p_quizzes) > 40 then raise exception 'Сұрақтар тізімі дұрыс емес'; end if;
  open_all := private.get_user_role(u) in ('teacher', 'admin')
    or exists (select 1 from public.level_runs lr where lr.user_id = u and lr.level_id = p_level and lr.status = 'finished');
  return coalesce((select jsonb_object_agg(e.quiz_id, jsonb_build_object('kk', e.kk, 'ru', e.ru))
    from private.trial_explanations e
    where e.level_id = p_level and e.quiz_id = any(p_quizzes)
      and (open_all or exists (select 1 from public.level_runs lr join private.level_run_answers a on a.run_id = lr.id
                               where lr.user_id = u and lr.level_id = p_level and a.quiz_id = e.quiz_id and a.attempts > 0))), '{}'::jsonb);
end $$;

revoke all on function public.trial_explain(int, text[]) from public, anon;
grant execute on function public.trial_explain(int, text[]) to authenticated;
`;
}

export const MIGRATION = new URL('../supabase/migrations/024_trial_explanations.sql', import.meta.url);
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const rows = await explanationRows();
  await writeFile(MIGRATION, explanationsSQL(rows));
  console.log(`024_trial_explanations.sql: ${rows.length} explanations`);
}
