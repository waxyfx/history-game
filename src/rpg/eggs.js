// Loose rock: a hint on a tap, opens on a hold (the hold length is set by applyWorld's ia(..., hold)).
export async function eggCrack(G, set, openFlag, hold, fxPos) {
  if (G.flags.b[openFlag]) return;
  if (!hold) return G.say(EGG_TEXT.crackHint);
  set(openFlag); G.sfx('secret'); G.E.tj_shake(8); if (fxPos) G.spawnFx?.(fxPos, 1, 14); G.forceNpc = true;
}
export async function eggFind(G, set, flag, lines, id) {
  if (G.flags.b[flag]) return G.say(EGG_TEXT.again);
  set(flag); await G.say(lines); anomaly(G, id);
}
export async function eggChess(G, set, openFlag) {
  if (G.flags.b[openFlag]) return G.say(EGG_TEXT.chessRight.slice(0, 1));
  await G.say(EGG_TEXT.chessIntro);
  const c = await G.choose(EGG_TEXT.chess);
  if (c !== EGG_TEXT.chess.correct) return G.say(EGG_TEXT.chessWrong);
  set(openFlag); G.sfx('secret'); G.E.tj_shake(6); G.forceNpc = true;
  return G.say(EGG_TEXT.chessRight);
}
